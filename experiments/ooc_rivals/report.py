"""Tables, figures and report.md from results/ooc_rivals/results.jsonl (see bench.py)."""
import json, os
from collections import defaultdict

LABEL = {"fa2": "FA-2 resident (R1)", "rect_ooc": "rect. OOC fixed (R2)", "rect_ooc_adaptive": "rect. OOC adaptive (R3)",
         "cqsa_auto": "Stream-CQSA auto"}
ORDER = ["fa2", "rect_ooc", "rect_ooc_adaptive", "cqsa_auto"]


def load(out_dir):
    rows = [json.loads(l) for l in open(os.path.join(out_dir, "results.jsonl"))]
    best = {}
    for r in rows:
        best[(r["method"], r["N"], r["direction"], float(r["budget_gib"]))] = r      # last row wins
    return best


def fmt_time(r):
    if r is None: return "-"
    if r["status"] != "ok": return r["status"].upper()
    t = r.get("warm_s") or r.get("cold_s")
    return f"{t:.1f}s ({r['peak_alloc_gib']:.1f}GiB)"


def choices_str(r):
    ch = r.get("choices") or {}
    if r["method"] == "cqsa_auto":
        info = ch.get("info") or {}
        return f"{ch.get('plan', '?')}; engine {info.get('engine')}, kernel {info.get('kernel')}, itr {info.get('itr')}, retries {r.get('retries')}"
    parts = []
    for d_, c in ch.items():
        parts.append(f"{d_}: q{c.get('tile_q')}/k{c.get('tile_k')} {c.get('traversal')}" + (f" probe {c.get('probe_s'):.2f}s" if c.get("probe_s") else ""))
    return "; ".join(parts)


def report(out_dir):
    best = load(out_dir)
    Ns = sorted({k[1] for k in best}); budgets = sorted({k[3] for k in best}); dirs = [d for d in ("fwd", "bwd") if any(k[2] == d for k in best)]
    L = ["# Automatic Stream-CQSA versus exact out-of-core rivals\n",
         "Generated by `experiments/ooc_rivals/report.py` from `results.jsonl`. One attention layer, B=1 H=8 D=64 fp16 causal; "
         "all methods start from host-resident Q/K/V (and dO) and end with host outputs / gradients; the device budget is the "
         "allocator cap and the planner's device description; median of 3 warm runs after one cold run (cold includes JIT, "
         "probing and planning). \"bwd\" = forward with its saved state + backward. Node/GPU per row in the JSONL.\n"]
    gpus = sorted({r.get("gpu", "?") for r in best.values()})
    L.append(f"GPUs used: {', '.join(gpus)}.\n")
    # 1. feasibility map + runtime
    for d_ in dirs:
        L.append(f"\n## Feasibility and runtime, {d_}\n\nCell = warm median time (peak allocated GiB); OOM / ERROR as recorded; '-' not run.\n")
        for b in budgets:
            L.append(f"\n**Budget {b:g} GiB**\n\n| N | " + " | ".join(LABEL[m] for m in ORDER) + " |\n|---|" + "---|" * len(ORDER))
            for N in Ns:
                L.append(f"| {N/1e6:.2f}M | " + " | ".join(fmt_time(best.get((m, N, d_, b))) for m in ORDER) + " |")
        # largest N completed per method and budget
        L.append(f"\n*Largest N completed ({d_}):*\n\n| budget | " + " | ".join(LABEL[m] for m in ORDER) + " |\n|---|" + "---|" * len(ORDER))
        for b in budgets:
            cells = []
            for m in ORDER:
                ok = [N for N in Ns if (r := best.get((m, N, d_, b))) and r["status"] == "ok"]
                cells.append(f"{max(ok)/1e6:.2f}M" if ok else "none")
            L.append(f"| {b:g} GiB | " + " | ".join(cells) + " |")
    # 2. automatic choices
    L.append("\n## Automatic configuration and rival tile choices\n\n| budget | N | dir | method | choices | cold s | warm s |\n|---|---|---|---|---|---|---|")
    for b in budgets:
        for N in Ns:
            for d_ in dirs:
                for m in ORDER:
                    r = best.get((m, N, d_, b))
                    if r and r["status"] == "ok" and m != "fa2":
                        L.append(f"| {b:g} | {N/1e6:.2f}M | {d_} | {LABEL[m]} | {choices_str(r)} | {r['cold_s']:.1f} | {r['warm_s']:.1f} |")
    # 3. data movement and phases
    L.append("\n## Data movement and phases\n\nBytes: 'counted' = transfers counted in the implementation; 'modelled' = from the plan (Stream-CQSA's engine is not byte-instrumented). Phases: summed device-stream durations (may overlap) and host merge time; wall time is the timing column above.\n")
    L.append("| budget | N | dir | method | H2D GiB | D2H GiB | kind | kernels | phases (s) |\n|---|---|---|---|---|---|---|---|---|")
    for b in budgets:
        for N in Ns:
            for d_ in dirs:
                for m in ORDER:
                    r = best.get((m, N, d_, b))
                    if r and r["status"] == "ok":
                        ph = r.get("phases") or {}
                        phs = "; ".join(f"{k}: " + ", ".join(f"{kk} {vv:.2f}" for kk, vv in v.items()) for k, v in ph.items()) if isinstance(ph, dict) else ""
                        L.append(f"| {b:g} | {N/1e6:.2f}M | {d_} | {LABEL[m]} | {(r.get('h2d_bytes') or 0)/2**30:.2f} | {(r.get('d2h_bytes') or 0)/2**30:.2f} | {r.get('bytes_kind')} | {r.get('n_kernels')} | {phs[:160]} |")
    # 4. correctness
    L.append("\n## Correctness\n\nForward: relative error against float64 on 128 sampled rows. Gradients: relative error of (dq, dk, dv) against the first method that finished the same N and budget (FlashAttention-2 where it fits). NaN/Inf counts are over outputs and gradients.\n")
    L.append("| budget | N | dir | method | fwd err | grad err (dq, dk, dv) | vs | NaN/Inf | budget breached |\n|---|---|---|---|---|---|---|---|---|")
    for b in budgets:
        for N in Ns:
            for d_ in dirs:
                for m in ORDER:
                    r = best.get((m, N, d_, b))
                    if r and r["status"] == "ok":
                        ge = r.get("err_grad_vs_ref")
                        L.append(f"| {b:g} | {N/1e6:.2f}M | {d_} | {LABEL[m]} | {r['err_fwd']:.1e} | " + (", ".join(f"{x:.1e}" for x in ge) if ge else "-") + f" | {r.get('grad_ref_method') or '-'} | {r.get('nan_inf')} | {r.get('budget_breached')} |")
    # 5. kernel-only reference
    ko = [(k, r) for k, r in best.items() if k[0] == "fa2" and r.get("kernel_only_s")]
    if ko:
        L.append("\n## Resident FlashAttention-2 kernel-only reference (no transfers; not comparable to the transfer-inclusive rows)\n\n| budget | N | kernel-only s | transfer-inclusive s |\n|---|---|---|---|")
        for (m, N, d_, b), r in sorted(ko, key=lambda kr: (kr[0][3], kr[0][1])):
            L.append(f"| {b:g} | {N/1e6:.2f}M | {r['kernel_only_s']:.2f} | {r.get('warm_s') or r.get('cold_s'):.2f} |")
    L.append("\n## Limitations\n\n* Kernels: the rivals run FlashAttention-2's forward/backward per tile; Stream-CQSA runs its own CQS-masked "
             "kernels (classic CUDA / wave / Triton as routed) and pays the quorum-set redundancy; FA-2 resident is the plain kernel. "
             "Precision is fp16 with fp32 accumulation for all.\n* A capped A100 80GB PCIe models a smaller capacity, not a smaller or "
             "slower device; nothing is claimed about edge hardware.\n* GQA and other head layouts were not run (unsupported by the shape used).\n"
             "* Full-model comparators (MEMO, FPDT, FlexGen) are out of scope; single-token decode is a different workload and is not included.\n")
    open(os.path.join(out_dir, "report.md"), "w").write("\n".join(L) + "\n")
    try:
        figures(best, Ns, budgets, dirs, out_dir)
    except Exception as e:      # noqa: BLE001
        print("figures skipped:", e)
    print("wrote", os.path.join(out_dir, "report.md"))


def figures(best, Ns, budgets, dirs, out_dir):
    import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
    fig, axes = plt.subplots(len(dirs), len(budgets), figsize=(5 * len(budgets), 4 * len(dirs)), squeeze=False)
    for i, d_ in enumerate(dirs):
        for j, b in enumerate(budgets):
            ax = axes[i, j]
            for m in ORDER:
                xs, ys = [], []
                for N in Ns:
                    r = best.get((m, N, d_, b))
                    if r and r["status"] == "ok":
                        xs.append(N / 1e6); ys.append(r.get("warm_s") or r.get("cold_s"))
                if xs: ax.plot(xs, ys, "o-", label=LABEL[m])
                fails = [N / 1e6 for N in Ns if (r := best.get((m, N, d_, b))) and r["status"] != "ok"]
                if fails: ax.plot(fails, [ax.get_ylim()[0] if ys else 1] * len(fails), "x", ms=8, color="gray")
            ax.set_xscale("log"); ax.set_yscale("log"); ax.set_title(f"{d_}, budget {b:g} GiB"); ax.set_xlabel("N (M tokens)"); ax.set_ylabel("time (s)")
            ax.grid(alpha=0.3); ax.legend(fontsize=7)
    fig.suptitle("Transfer-inclusive time from host inputs to host outputs (x = OOM/error)"); fig.tight_layout()
    fig.savefig(os.path.join(out_dir, "runtime_vs_N.png"), dpi=110)
    # feasibility map: N vs budget, per method
    fig, axes = plt.subplots(len(dirs), len(ORDER), figsize=(4 * len(ORDER), 3.5 * len(dirs)), squeeze=False)
    for i, d_ in enumerate(dirs):
        for j, m in enumerate(ORDER):
            ax = axes[i, j]
            for bi, b in enumerate(budgets):
                for ni, N in enumerate(Ns):
                    r = best.get((m, N, d_, b))
                    if r is None: continue
                    ok = r["status"] == "ok"
                    ax.scatter(N / 1e6, b, marker="o" if ok else "x", s=120, color="tab:green" if ok else "tab:red")
                    if ok: ax.annotate(f"{(r.get('warm_s') or r.get('cold_s')):.0f}s", (N / 1e6, b), fontsize=7, ha="center", va="bottom")
            ax.set_xscale("log"); ax.set_title(f"{LABEL[m]}, {d_}"); ax.set_xlabel("N (M tokens)"); ax.set_ylabel("budget (GiB)"); ax.grid(alpha=0.3)
    fig.suptitle("Feasibility map: green = completed (runtime), red x = OOM / error"); fig.tight_layout()
    fig.savefig(os.path.join(out_dir, "feasibility_map.png"), dpi=110)


if __name__ == "__main__":
    import sys
    report(sys.argv[1] if len(sys.argv) > 1 else "results/ooc_rivals")
