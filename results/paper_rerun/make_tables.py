"""
Paper re-run tables (A100 80GB PCIe) from the frozen result files in this directory.

    python results/paper_rerun/make_tables.py        # writes tables_native.md and tables_triton.md

Port of the dev tree's `next/bench/paper_tables.py --md` (same cells: warm time / peak allocated device
memory / decomposition depth; same method columns) with three changes: cells without a measurement say
"not run" (never "OOM"), each not-run cell gets its reason as a footnote, and the ratio column is named
for what it is (time of Stream-CQSA's faster arm divided by FlashAttention-2's time; > 1 = slower).
Inputs: results_native.jsonl (native v11 CUDA kernel, jobs cqsa_p_*), results_triton.jsonl (Triton
kernels, jobs cqsa_pt_*); rows accumulate over the jobs listed in README.md, the last row per
(method, dtype, direction, N) wins.
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
GPU = "A100 80GB PCIe"
SETS = [("native", "native CUDA kernel (v11 causal / v9 non-causal build)", "results_native.jsonl"),
        ("triton", "Triton kernels (CQSA_FORWARD=triton CQSA_BACKWARD=triton)", "results_triton.jsonl")]
METHS = [("flash", "FlashAttention-2"), ("sdpa_mem", "SDPA mem-eff."), ("cqsa_accgpu", "Stream-CQSA acc=GPU"),
         ("cqsa_acccpu", "Stream-CQSA acc=CPU")]
DEVICE_GIB = 79.3


def load(p):
    best = {}
    for l in open(p):
        r = json.loads(l); best[(r["method"], r["dtype"], r["direction"], r["N"])] = r    # last row wins
    return best


def fmt(r):
    if r is None: return "not run"
    if r["status"] != "ok": return "OOM" if r["status"] == "oom" or "memory" in (r["error"] or "").lower() else r["status"]
    i = r.get("info", {}); itr = i.get("itr"); b = i.get("bwd_itr_reached")
    tag = (f"/itr{itr}" + (f"+b{b}" if b not in (None, itr) else "")) if "cqsa" in r["method"] else ""
    return f"{r['ms']/1e3:.1f}s/{r['mem_alloc_peak']/1024:.1f}GiB{tag}"


def not_run_reason(d, m, dtype, direction, N):
    """Why a cell has no row: predicted device need beyond the GPU, or a run time that was not spent."""
    known = sorted((k[3], r) for k, r in d.items() if k[:3] == (m, dtype, direction) and r["status"] == "ok")
    if m == "sdpa_mem" and direction == "bwd" and known:
        n0, r0 = known[-1]
        t = r0["ms"] / 1e3 * (N / n0) ** 2
        return (f"not run: the mem-efficient SDPA backward took {r0['ms']/1e3:.0f} s at {n0/1e6:.1f}M "
                f"(quadratic: ~{t/3600:.0f} h at {N/1e6:.1f}M)")
    if m in ("flash", "sdpa_mem") and known:
        n0, r0 = known[-1]
        need = r0["mem_alloc_peak"] / 1024 * N / n0
        if need > DEVICE_GIB:
            return f"not run: device need ~{need:.1f} GiB (linear from {r0['mem_alloc_peak']/1024:.1f} GiB at {n0/1e6:.1f}M) > {DEVICE_GIB} GiB"
    if m == "cqsa_accgpu" and direction == "bwd":
        acc = 3 * N * 8 * 64 * 4 / 2**30
        return (f"not run: acc=GPU keeps three fp32 dQ/dK/dV accumulators on the device, {acc:.0f} GiB > {DEVICE_GIB} GiB "
                f"(the xl job ran acc=CPU only)")
    if dtype == "bfloat16":
        return "not run: the bfloat16 series stops at 8.4M forward / 4.2M forward+backward"
    return "not run (no row in the result file)"


def markdown(key, name, path, min_N=1 << 18):
    d = load(os.path.join(HERE, path))
    out = [f"# Paper re-run tables: {name}\n",
           f"GPU: {GPU} (79.3 GiB), torch 2.10.0+cu130, flash-attn 2.8.3; B=1 H=8 D=64, causal. Generated by "
           f"`results/paper_rerun/make_tables.py` from `{path}`. Cell = time / peak allocated device memory / depth "
           f"(`itr1+b3`: the backward escalated to depth 3). Ratio = Stream-CQSA's faster arm divided by FlashAttention-2's "
           f"time (> 1 = Stream-CQSA slower), only where both completed.\n"]
    notes = []
    for dtype in ("float16", "bfloat16"):
        if not any(k[1] == dtype for k in d): continue
        Ns = [N for N in sorted({k[3] for k in d}) if N >= min_N]
        for direction, what in (("fwd", "forward"), ("bwd", "forward + backward")):
            out.append(f"\n**{name}, {dtype}, {what}**\n")
            out.append("| N | FlashAttention-2 | SDPA mem-eff. | Stream-CQSA acc=GPU | Stream-CQSA acc=CPU | time ratio vs FA-2 |")
            out.append("|---|---|---|---|---|---|")
            for N in Ns:
                rows = [d.get((m, dtype, direction, N)) for m, _ in METHS]
                if all(r is None for r in rows): continue
                cells = []
                for (m, _), r in zip(METHS, rows):
                    c = fmt(r)
                    if r is None:
                        notes.append(not_run_reason(d, m, dtype, direction, N) + f" [{dict(METHS)[m]}, {dtype}, {what}, {N/1e6:.1f}M]")
                        c += f" [{len(notes)}]"
                    cells.append(c)
                fa = rows[0]; cq = [r for r in rows[2:] if r and r["status"] == "ok"]
                ratio = f"{min(r['ms'] for r in cq) / fa['ms']:.2f}x" if fa and fa["status"] == "ok" and cq else ("only Stream-CQSA completes" if cq else "-")
                out.append(f"| {N/1e6:.1f}M | " + " | ".join(cells) + f" | {ratio} |")
        out.append(f"\n**{name}, {dtype}, forward accuracy vs float64** (relative error on 128 sampled rows)\n")
        out.append("| N | FlashAttention-2 | SDPA mem-eff. | Stream-CQSA acc=GPU | Stream-CQSA acc=CPU |")
        out.append("|---|---|---|---|---|")
        for N in Ns:
            row = [d.get((m, dtype, "fwd", N)) for m, _ in METHS]
            if all(r is None for r in row): continue
            out.append(f"| {N/1e6:.1f}M | " + " | ".join(f"{r['acc_rel']:.1e}" if r and r.get("acc_rel") is not None and r.get("acc_rel") == r.get("acc_rel") else "not run" for r in row) + " |")
    if notes:
        out.append("\nNot-run cells:\n")
        out += [f"{i}. {n}" for i, n in enumerate(notes, 1)]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    for key, name, path in SETS:
        p = os.path.join(HERE, f"tables_{key}.md")
        open(p, "w").write(markdown(key, name, path))
        print("wrote", p)
